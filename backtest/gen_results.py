#!/usr/bin/env python3
"""Regenerate RESULTS.md from the live engine so it cannot go stale silently.
   python gen_results.py > RESULTS.md"""
import sys, statistics, math, datetime as dt; sys.path.insert(0,'.')
import engine as E, engine_v2 as V
from noise_math import expected_max_normal

bars=E.load_bars("data/btc_4h.csv"); e20,e120,atr=E.indicators(bars)
FIRST=dt.datetime.fromtimestamp(E.T0, dt.timezone.utc); LAST=dt.datetime.fromtimestamp(E.T0+(len(bars)-1)*E.STEP, dt.timezone.utc)
SPAN=f"{FIRST:%b %-d} - {LAST:%b %-d %Y}"
FEED=next((r[0].lstrip("# ").split(",")[0] for r in __import__("csv").reader(open("data/btc_4h.csv")) if r and r[0].startswith("#")), "o,h,l,c file")
warm=max(E.EMA_TREND+E.TREND_SLOPE_BARS,V.RANGE_BARS)+1
MONTHS=(len(bars)-warm)*4/24/30.44

CONFIGS=[("v1 pullback, no filter",      dict(REGIME=0,BREAKOUT=0,LADDER=0,REVERSE_AFTER_TP3=0)),
         ("+ regime filter",             dict(REGIME=1,BREAKOUT=0,LADDER=0,REVERSE_AFTER_TP3=0)),
         ("+ breakout, single entry",    dict(REGIME=1,BREAKOUT=1,LADDER=0,REVERSE_AFTER_TP3=0)),
         ("3-tranche weakness ladder",   dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="weakness",LADDER_N=3,REVERSE_AFTER_TP3=0)),
         ("5-tranche weakness ladder",   dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="weakness",LADDER_N=5,REVERSE_AFTER_TP3=0)),
         ("3-tranche strength ladder",   dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="strength",LADDER_N=3,REVERSE_AFTER_TP3=0)),
         ("5-tranche strength ladder",   dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="strength",LADDER_N=5,REVERSE_AFTER_TP3=0)),
         ("5-strength + reverse on TP3", dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="strength",LADDER_N=5,REVERSE_AFTER_TP3=1,REVERSE_TRIGGER="tp3")),
         ("5-strength + reverse on stop",dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="strength",LADDER_N=5,REVERSE_AFTER_TP3=1,REVERSE_TRIGGER="stop")),
         ("5-strength + reverse on any", dict(REGIME=1,BREAKOUT=1,LADDER=1,LADDER_DIR="strength",LADDER_N=5,REVERSE_AFTER_TP3=1,REVERSE_TRIGGER="any"))]

def apply(cfg):
    V.HOLDING="swing_safe"; V.BREAKEVEN_AFTER_TP1=True
    V.LADDER_DIR="strength"; V.LADDER_N=5; V.REVERSE_TRIGGER="tp3"
    for k,v in cfg.items(): setattr(V,k,bool(v) if k in("REGIME","BREAKOUT","LADDER","REVERSE_AFTER_TP3") else v)

print(f"""# Results — BTCUSDT 4h, {len(bars)} bars ({SPAN})

**Generated by `gen_results.py` from the live engine. Do not hand-edit — regenerate.**

Data: `data/btc_4h.csv` — {FEED}. One feed end to end; the daily shadow extends the same
file from the same feed (`stitch_bars.py`).

Account: Bitfunded Expert $100,000, 1-Step. 4% daily loss, a fixed $4,000 from the initial
balance (Bitfunded FAQ), 6% static floor at $94,000, 0.04%/side fees, 5x max leverage.
Holding policy `swing_safe`, desk sizing (0.5% of balance capped at 35% of the effective budget).

Engine state: entry-bar reorder applied, merged reset block (flatten -> old-day check ->
roll the day -> rollover vs the fixed limit), zombie outcome.

## Continuous run, 0.5% risk per trade

| configuration | n | trades/mo | win | exp R | PF | max DD | fills W/L |
|---|---|---|---|---|---|---|---|""")
rows=[]
for label,cfg in CONFIGS:
    apply(cfg)
    sg=V.build_signals(bars,e20,e120,atr); r=V.run(bars,sg,warm,challenge=False,atr=atr)
    st=E.trade_stats(r.trades)
    w=[t['fills'] for t in r.trades if t['pnl']>0]; l=[t['fills'] for t in r.trades if t['pnl']<=0]
    f=f"{statistics.mean(w):.2f} / {statistics.mean(l):.2f}" if (w and l and V.LADDER) else "—"
    rows.append((label,st,r))
    print(f"| {label} | {st['n']} | {st['n']/MONTHS:.1f} | {st['win_rate']:.0f}% | "
          f"{st['exp_r']:+.2f} | {st['profit_factor']:.2f} | ${r.trough_dd:,.0f} | {f} |")

best=max(rows,key=lambda x:x[1]['exp_r'])
rs=[t['r'] for t in best[2].trades]
sd=statistics.stdev(rs); se=sd/math.sqrt(len(rs)); m=statistics.mean(rs)

print(f"""
## Is the best configuration real?

Best: **{best[0]}** at {m:+.3f}R.

- n = {len(rs)}, sd = {sd:.2f}R, standard error = **{se:.3f}R**
- t = {m/se:.2f}, 95% CI **[{m-1.96*se:+.3f}R, {m+1.96*se:+.3f}R]** — contains zero
- ~30 configurations were tested on this one sample. Under a true zero edge the
  best of 30 would be expected around **+{expected_max_normal(30)*se:.2f}R** by chance. The observed
  {m:+.3f}R is *below* that.

**No configuration in this table is distinguishable from zero.** Every number here is a
hypothesis for the walk-forward, not a result.

## What does hold regardless of expectancy

1. **Ladder direction is the largest structural effect found.** Same signals, same
   stops, only the side the tranches sit on. Weakness at 5 tranches gives the worst
   profit factor in the project; strength at 5 gives the lowest drawdown.
2. **A strength ladder holds ~34% LESS quantity than a single entry** at the same risk
   (0.109 vs 0.167 BTC on a 1.5-ATR stop). Its benefit is conditionality, not size:
   small when wrong, large when right. It is not a way to take a bigger position.
3. **Intraday holding is self-defeating on a 4h chart** — roughly half of all trades get
   force-flattened at the 16:00 UTC reset before they resolve, and pay fees to do it.
4. **The budget cap is what makes the account survivable.** At +0.35R, naive sizing at
   1% blows the account 68% of the time in a year; at 2%, 100%. Under the cap, 0%
   (MODELLED: income_math.py, 20,000 simulated years; verify_claims.py reproduces it).
5. **The rollover trap** (below): no configuration carried a floating loss across a reset
   that broke the daily limit on this sample; the closest needed uncapped risk and a policy
   that holds losers through the reset together.""")

# The chosen configuration (strategy_config.json: 5-strength + reverse on stop) over rolling challenge starts: a start
# every 18 bars (3 days), each run to the end of the sample, in challenge mode with desk sizing.
CHOSEN = 8
apply(CONFIGS[CHOSEN][1]); V.HOLDING = "swing_safe"
sg = V.build_signals(bars, e20, e120, atr)
STARTS = list(range(warm, len(bars) - 120, 18))
runs = [V.run(bars, sg, s0, atr=atr) for s0 in STARTS]
oc = {}
for x in runs: oc[x.outcome] = oc.get(x.outcome, 0) + 1
print(f"""
## Rolling challenge starts, the chosen configuration

**{CONFIGS[CHOSEN][0]}**, desk sizing, `swing_safe`: {len(runs)} starts, one every 18 bars (3 days), each run to the
end of the sample. Outcomes: {", ".join(f"{k} {v}" for k, v in sorted(oc.items()))}. Median ending balance
**${statistics.median(x.balance for x in runs):,.0f}** (from $100,000).""")

# The rollover trap: the largest floating loss carried into a reset (after the holding policy's flatten), and how many
# starts broke the daily limit with it, by sizing and holding policy, across every configuration.
TRAP = [("desk sizing (0.5%, capped)", 0.005, True), ("4% uncapped", 0.04, False)]
print("""
## The rollover trap

The largest floating loss carried into a daily reset, against the fixed $4,000 line, over the same rolling starts:

| holding | sizing | worst over every configuration | starts that broke the limit at a reset |
|---|---|---|---|""")
for hold, what in (("swing_safe", "swing_safe (a loser is closed before the reset)"), ("swing", "swing (a loser is held through it)")):
    for sname, rp, cap in TRAP:
        worst, breaches = 0.0, 0
        for label, cfg in CONFIGS:
            apply(cfg); V.HOLDING = hold
            sgx = V.build_signals(bars, e20, e120, atr)
            rr = [V.run(bars, sgx, s0, risk_pct=rp, capped=cap, atr=atr) for s0 in STARTS]
            worst = min(worst, min(x.worst_reset_float for x in rr)); breaches += sum(x.rollover_breach for x in rr)
        print(f"| {what} | {sname} | ${max(0.0, -worst):,.0f} | {breaches} of {len(STARTS) * len(CONFIGS)} |")
V.HOLDING = "swing_safe"

# The reversal trigger: how often each trigger fired (trades of kind "reverse") in the continuous run, and how many of
# the base ladder's trades reached their third target.
print("""
## The reversal trigger

| configuration | trades | reverse trades | trades that reached the third target |
|---|---|---|---|""")
for label, st, r in rows[6:]:
    tr = r.trades; tp3 = sum(1 for t in tr if t["tps_hit"] >= 3)
    print(f"| {label} | {len(tr)} | {sum(1 for t in tr if t['kind'] == 'reverse')} | {tp3} ({100 * tp3 / len(tr):.1f}%) |")

# Frequency: the chosen configuration's, and what an income target needs at it. DERIVED: gross a month per account =
# exp R x trades a month x the $500 risk (0.5% of $100,000), before the split, fees and any breach.
TPM = rows[CHOSEN][1]["n"] / MONTHS
print(f"""
## Frequency, and what it costs

The chosen configuration produces **{TPM:.1f} trades/month**. Earlier income modelling assumed 30 a month (an
assumption, never measured). DERIVED: gross a month per account = exp R x trades a month x $500 risk (0.5% of
$100,000), before the split, fees and any breach:

| edge | trades/mo | gross/account/mo | accounts for $6,250/mo |
|---|---|---|---|""")
for er in (0.15, 0.35):
    for tpm, lab in ((TPM, f"{TPM:.1f} (measured)"), (30, "30 (assumed)")):
        g = er * tpm * 500
        print(f"| +{er:.2f}R | {lab} | ${g:,.0f} | {6250 / g:.1f} |")
print(f"""
At the measured frequency the account requirement is about {30 / TPM:.1f} times the assumed one.
""")
print(f"""## Not established

Anything outside these {MONTHS:.1f} months, this one asset, this one regime. The
walk-forward in `HANDOFF.md` is the gate on every number above.
""")

